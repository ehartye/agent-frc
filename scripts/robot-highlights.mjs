import { checkChapters, clipTime } from './replay-chapters.mjs';
import { inlineThemeFonts } from './theme-fonts.mjs';
import {publicFusionHandoff} from './public-fusion-handoff.mjs';
import { workflowRows } from './project-layout.mjs';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { createHash, randomUUID } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { copyFile, mkdir, readFile, realpath, rename, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const marker = '<!-- Generated by Agent FRC robot-highlights -->';
const kinds = new Set(['modeled', 'measured', 'design', 'open']);
const assetTypes = new Set(['.csv', '.json', '.txt', '.pdf', '.jpg', '.jpeg', '.png', '.webp', '.mp4', '.webm']);
const escape = value => String(value).replace(/[&<>"']/g, char => ({'&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;'}[char]));
function requireValue(ok, message) { if (!ok) throw Error(message); }
function string(value, key) {
  requireValue(typeof value === 'string' && value.trim(), 'Missing ' + key);
  return value;
}
function list(value, key, required = false) {
  requireValue(Array.isArray(value) && (!required || value.length), 'Invalid ' + key);
  return value;
}
async function digest(file) {
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(file)) hash.update(chunk);
  return hash.digest('hex');
}
function within(root, file) {
  const relative = path.relative(root, file);
  return relative !== '..' && !relative.startsWith('..' + path.sep) && !path.isAbsolute(relative);
}
async function optionalRead(file) {
  try { return await readFile(file, 'utf8'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
}

export async function buildHighlights(manifest, directory) {
  const authorizeModel=async (python,root,request)=>{
    const checker=fileURLToPath(new URL('./showcase_release.py',import.meta.url));
    await promisify(execFile)(python,[checker,root,JSON.stringify(request)],{encoding:'utf8'});
  };
  const root = await realpath(path.dirname(manifest));
  const data = JSON.parse(await readFile(manifest, 'utf8'));
  requireValue(data.schema === 'agent-frc/robot-highlights@1', 'Unknown highlights schema');
  const title = escape(string(data.title, 'robot name'));
  const role = escape(string(data.role, 'robot role'));
  const revision = escape(string(data.revision, 'current candidate revision'));
  const stage = data.stage ?? 'design';
  requireValue(['analysis', 'design'].includes(stage), 'Unknown showcase stage');
  const assets = new Map();
  const python = process.env.PYTHON || (process.platform === 'win32' ? 'python' : 'python3');
  async function projectFile(relative) {
    requireValue(typeof relative === 'string' && !path.win32.isAbsolute(relative) && !path.isAbsolute(relative), 'Expected project-relative file');
    const file = await realpath(path.resolve(root, relative));
    requireValue(within(root, file) && (await stat(file)).isFile(), 'File outside project');
    return file;
  }
  let stylesheet;
  if (data.stylesheet !== undefined) {
    const css = data.stylesheet;
    requireValue(css?.shareable === true && typeof css.file === 'string' &&
      css.file.endsWith('.css') && !path.win32.isAbsolute(css.file) && !path.isAbsolute(css.file),
      'Expected a shareable project-relative stylesheet');
    const file = await realpath(path.resolve(root, css.file));
    requireValue(within(root, file) && (await stat(file)).isFile() && /^[a-f0-9]{64}$/.test(css.sha256) &&
      await digest(file) === css.sha256, 'Changed or invalid project stylesheet');
    stylesheet = css.sha256 + '.css';
    assets.set(stylesheet, file);
  }
  function applyStyle(markup, base = '') {
    if (!stylesheet) return markup;
    return markup.replace('</head>', '<link rel="stylesheet" href="' + base + 'evidence/' + stylesheet + '"></head>');
  }
  function backdrop(config) {
    if (!Object.hasOwn(config, 'backdrop')) return undefined;
    const value = config.backdrop;
    requireValue(value && Object.keys(value).length === 2 &&
      [value.center, value.edge].every(color => typeof color === 'string' && /^#[0-9a-f]{6}$/i.test(color)),
      'Invalid CAD backdrop');
    return {center: value.center.toUpperCase(), edge: value.edge.toUpperCase()};
  }
  const sources = new Map();
  for (const ref of list(data.sources, 'sources', true)) {
    const id = string(ref.id, 'source ID');
    requireValue(!sources.has(id), 'Duplicate source ' + id);
    const label = string(ref.label, 'source label');
    const version = string(ref.revision, 'source revision');
    let href, type;
    if (ref.file !== undefined) {
      requireValue(!ref.url && ref.shareable === true, 'Confirm redistribution for ' + id);
      const name = string(ref.file, 'source file');
      requireValue(!path.win32.isAbsolute(name) && !path.isAbsolute(name), 'Expected relative file for ' + id);
      const file = await realpath(path.resolve(root, name));
      requireValue(within(root, file) && (await stat(file)).isFile(), 'Source outside project ' + id);
      type = path.extname(file).toLowerCase();
      requireValue(assetTypes.has(type), 'Unsupported evidence file type ' + type);
      requireValue(/^[a-f0-9]{64}$/.test(ref.sha256) && await digest(file) === ref.sha256, 'Changed evidence ' + id);
      const dest = ref.sha256 + type;
      href = 'evidence/' + dest;
      assets.set(dest, file);
    } else {
      const url = new URL(string(ref.url, 'evidence URL'));
      requireValue(url.protocol === 'https:' && !url.username && !url.password, 'Expected public HTTPS evidence URL');
      href = url.href;
    }
    sources.set(id, {label, version, href, type, sha256:ref.sha256});
  }
  function source(id) {
    requireValue(sources.has(id), 'Unknown evidence reference ' + id);
    return sources.get(id);
  }
  function citation(id) {
    const s = source(id);
    return '<a href="' + escape(s.href) + '">' + escape(s.label) + '</a> <small>· ' + escape(s.version) + '</small>';
  }
  function kind(row) {
    requireValue(kinds.has(row.basis), 'Invalid evidence basis');
    return '<span class="basis">' + row.basis + '</span>';
  }
  const results = list(data.results, 'results', true).map(row =>
    '<article>' + kind(row) + '<h3>' + escape(string(row.claim, 'result')) + '</h3><p>' +
    escape(string(row.conditions, 'run conditions')) + '</p><p>' + escape(string(row.limit, 'result boundary')) +
    '</p><p>' + citation(row.source) + '</p></article>').join('');
  const build = list(data.build ?? (stage === 'analysis' ? [] : undefined), 'build sheet', stage !== 'analysis').map(row =>
    '<tr><th scope="row">' + escape(string(row.subsystem, 'subsystem')) + '</th><td>' +
    escape(string(row.configuration, 'configuration')) + '</td><td>' + citation(row.source) + '</td></tr>').join('');
  const eventRecords = new Map();
  async function replay(motion, clip) {
    const evidence = source(motion.observations);
    const trace = source(motion.trace);
    requireValue(trace.sha256 && trace.href !== clip.href && evidence.href !== clip.href && evidence.href !== trace.href && evidence.type === '.json',
      'Motion needs a trace and separate local observation evidence');
    if (!eventRecords.has(evidence.href)) {
      eventRecords.set(evidence.href, JSON.parse(await readFile(assets.get(path.basename(evidence.href)), 'utf8')));
    }
    const record = eventRecords.get(evidence.href);
    requireValue(record.schema === 'agent-frc/replay-events@1' && record.revision === data.revision &&
      record.clock === string(motion.clock, 'run clock') && record.attempt === string(motion.attempt, 'attempt'),
      'Playback revision, attempt or clock differs from evidence');
    requireValue(record.clipSha256 === clip.sha256 && record.traceSha256 === trace.sha256,
      'Observation register does not reference this clip and motion trace');
    const observedRevision = string(record.observedRevision, 'observed revision');
    const piece = string(record.piece,'piece identity');
    const start = string(record.initialState,'initial state or checkpoint');
    requireValue(['same-attempt','independent-start','earlier-revision','capacity-only'].includes(record.scope) &&
      (observedRevision === data.revision || record.scope === 'earlier-revision'),
      'Identify earlier-revision evidence separately');
    const anchors = list(record.sync, 'clock synchronization', true);
    requireValue(anchors.length >= 2 && anchors[0].clipS === 0 && anchors.every((point,i) =>
      Number.isFinite(point.clipS) && Number.isFinite(point.runS) &&
      (i === 0 || point.clipS > anchors[i-1].clipS && point.runS > anchors[i-1].runS)),
      'Clip and experiment clocks need increasing synchronization points');
    const mode = motion.basis;
    requireValue(['commanded','simulated','measured'].includes(mode), 'Invalid motion basis');
    const seen = new Set();
    const events = list(record.events,'observed events',true).map(event => {
      const id = string(event.id,'event ID');
      requireValue(!seen.has(id) && Number.isFinite(event.timeS), 'Invalid observed event time or repeated ID');
      seen.add(id);
      requireValue(['reached','scored','missed','unresolved'].includes(event.outcome), 'Invalid observed outcome');
      requireValue(record.scope !== 'capacity-only' || event.outcome === 'unresolved', 'A capacity target cannot establish a reached outcome');
      const clipAt = clipTime(anchors,event.timeS);
      const label = escape(string(event.target,'observed target'));
      return '<li><button type="button" data-clip-time="'+clipAt+'">Seek to '+clipAt.toFixed(2)+' s</button> '+
        label+' · <strong>'+event.outcome+'</strong> · '+escape(record.clock)+' '+event.timeS+' s. '+
        escape(string(event.criterion,'observation criterion'))+'</li>';
    }).join('');
    return '<p>'+escape(string(motion.movingPart,'moving part'))+' · '+mode+' motion · '+citation(motion.trace)+
      '</p><p>Source-declared event register · observed revision '+escape(observedRevision)+' · '+escape(record.scope)+' · piece '+escape(piece)+' · start '+escape(start)+'</p><ul class="events">'+events+'</ul><p>Event observations · '+citation(motion.observations)+
      '</p><p class="seek-status" role="status"></p>';
  }
  const pageObservations=new Map();
  function eventLabel(e) {
    const first=pageObservations.get(e.observationKey);
    const facts=JSON.stringify([e.type,e.target,e.criterion,e.rule,e.observedOutcome??e.outcome,e.timeS]);
    if (first) {
      requireValue(first.facts===facts,'Conflicting values for the same independent observation across films');
      return e.target+' · another view of '+first.id;
    }
    pageObservations.set(e.observationKey,{id:e.id,facts});
    return e.target+' · '+e.outcome;
  }
  async function chapterList(spec, asset) {
    const register=source(spec.register), trace=source(spec.trace), observations=source(spec.observations);
    requireValue([register,trace,observations].every(s=>s.type==='.json' && s.sha256),'Expected local checked chapter records');
    const result=await checkChapters(assets.get(path.basename(register.href)),root);
    requireValue(result.revision===data.revision && result.mediaSha256===asset.sha256 &&
      result.traceSha256===trace.sha256 && result.observationsSha256===observations.sha256,
      'Chapter register differs from displayed media, revision or sources');
    const seek=(time,label)=>'<button type="button" data-clip-time="'+time+'">'+escape(label)+'</button>';
    const rows=result.chapters.map(c=>'<li>'+seek(c.startS,c.label)+' · '+escape(c.classification)+
      '<p>'+[c.revision,c.attempt,c.piece,c.clock].map(escape).join(' · ')+'</p><ul>'+c.events.map(e=>
        '<li>'+seek(e.clipS,eventLabel(e))+' · '+escape(e.type)+' · '+escape(c.clock)+' '+e.timeS+
        ' s · '+escape(e.criterion)+(e.rule?' · '+escape(e.rule):'')+'</li>').join('')+'</ul></li>');
    return '<h3>Replay chapters</h3><ol>'+rows.join('')+'</ol><p>Checkpoints · '+citation(spec.trace)+
      ' · Event observations · '+citation(spec.observations)+' · '+citation(spec.register)+'</p><p class="seek-status" role="status"></p>';
  }
  let media='';
  for (const row of list(data.media ?? [], 'media')) {
    const asset = source(row.asset);
    const caption = escape(string(row.caption, 'media description'));
    const alt = escape(string(row.description, 'media alternative'));
    requireValue(!(row.chapters && row.motion),'Choose a chapter register or a single motion record');
    let item;
    if (['.mp4', '.webm'].includes(asset.type)) {
      let poster = '';
      if (row.poster) {
        const image = source(row.poster);
        requireValue(['.png','.jpg','.jpeg','.webp'].includes(image.type), 'Expected local poster image');
        poster = ' poster="' + escape(image.href) + '"';
      }
      item = '<video controls playsinline preload="metadata" aria-label="' + alt + '"' + poster + ' src="' + escape(asset.href) + '"></video>';
    } else {
      requireValue(!row.motion && !row.chapters, 'Motion playback requires a local video');
      requireValue(['.png','.jpg','.jpeg','.webp'].includes(asset.type), 'Expected local evidence image or film');
      item = '<img loading="lazy" alt="' + alt + '" src="' + escape(asset.href) + '">';
    }
    media += '<figure>' + item + '<figcaption>' + caption + ' · ' + citation(row.source) + '</figcaption>' +
      (row.chapters ? await chapterList(row.chapters,asset) : row.motion ? await replay(row.motion,asset) : '') + '</figure>';
  }
  let campaign = '';
  if (data.campaign !== undefined) {
    const c = data.campaign;
    const counts = [c.total,c.passed,c.failed,c.unresolved,c.required];
    requireValue(counts.every(n => Number.isSafeInteger(n) && n >= 0) && c.required > 0 &&
      c.required <= c.total && c.passed + c.failed + c.unresolved === c.total, 'Invalid campaign counts');
    campaign = '<section id="campaign"><h2>Repeatability</h2><h3>' + escape(string(c.criterion,'campaign criterion')) +
      '</h3><p>Target ' + c.required + ' of ' + c.total + ' attempts. ' + c.passed + ' passed, ' + c.failed +
      ' failed, ' + c.unresolved + ' unresolved.</p><p>' + citation(c.source) + '</p></section>';
  }
  const template = await readFile(new URL('../templates/robot-highlights.html', import.meta.url), 'utf8');
  let model = '';
  let modelFiles,release;
  if (data.cad) {
    const config = data.cad;
    requireValue(config.shareable === true, 'Confirm CAD redistribution');
    const receiptFile = await projectFile(config.receipt);
    const record = JSON.parse(await readFile(receiptFile,'utf8'));
    requireValue(['agent-frc/cad-still@1','agent-frc/cad-still@2'].includes(record.schema) && await digest(await projectFile(record.source)) === record.sourceSha256,'Changed CAD source');
    let captureReview=config.captureReview,readiness=config.mechanicalReadiness ?? data.mechanicalReadiness;
    const selectedFile = path.join(root,'cad-showcase.json');
    const selectedText = await optionalRead(selectedFile);
    if (selectedText !== undefined) {
      const selected = JSON.parse(selectedText.replace(/^\uFEFF/, ''));
      // A showcase can also feature a separately registered historical assembly.
      if (selected.source === record.source || path.normalize(config.receipt) === path.join('docs','robot','cad','receipt.json')) {
        requireValue(selected.source === record.source, 'Selected CAD source differs from the export');
        requireValue(JSON.stringify(backdrop(selected)) === JSON.stringify(backdrop(record)), 'Selected backdrop differs from the CAD export');
        if(selected.captureReview!==undefined){
          requireValue(captureReview===undefined||captureReview===selected.captureReview,'Selected capture review differs from the showcase');
          captureReview=selected.captureReview;
        }
        if(selected.mechanicalReadiness!==undefined){
          requireValue(!readiness || JSON.stringify(readiness)===JSON.stringify(selected.mechanicalReadiness),'Selected mechanical readiness differs from the showcase');
          readiness=selected.mechanicalReadiness;
        }
        const colored = record.schema === 'agent-frc/cad-still@2';
        requireValue(Object.hasOwn(selected,'appearances') === colored &&
          (!colored || selected.appearances === record.appearances?.file), 'Selected appearance manifest differs from the export');
      }
    }
    const folder = path.dirname(config.receipt);
    const still = await projectFile(path.join(folder,'assembly.png'));
    const mesh = await projectFile(path.join(folder,'assembly.stl.gz'));
    requireValue(await digest(still) === record.imageSha256 && await digest(mesh) === record.meshSha256, 'Changed CAD export');
    requireValue(Array.isArray(record.nativeBounds) && record.nativeBounds.length === 6 && record.nativeBounds.every(Number.isFinite), 'Invalid CAD bounds');
    if(captureReview!==undefined){
      await projectFile(captureReview);
      const checker=fileURLToPath(new URL('./cad_capture.py',import.meta.url));
      await promisify(execFile)(python,[checker,root,captureReview,'--source-sha256',record.sourceSha256,'--image-sha256',record.imageSha256],{encoding:'utf8'});
    }
    let layout = record.nativeBounds;
    if (record.schema === 'agent-frc/cad-still@2') {
      await projectFile(record.appearances?.file);
      const validator = fileURLToPath(new URL('./cad_appearances.py',import.meta.url));
      const {stdout} = await promisify(execFile)(python,[validator,root,receiptFile],{encoding:'utf8'});
      layout = {bounds:record.nativeBounds, groups:JSON.parse(stdout)};
    }
    if (backdrop(record)) layout = {...(Array.isArray(layout) ? {bounds: layout} : layout), backdrop: backdrop(record)};
    const values = {title:escape(string(config.title,'assembly name')), scope:escape(string(config.scope,'CAD scope')),
      facts:escape(record.solids+' solids · '+record.triangles+' triangles · '+record.chordMm+' mm chord setting'),
      bounds:JSON.stringify(layout), mesh:(await readFile(mesh)).toString('base64')};
    const viewer = await readFile(new URL('../templates/cad-orbit.html',import.meta.url),'utf8');
    // Content-address the viewer directory so a later generation cannot change an earlier page's model.
    const rendered = applyStyle(viewer.replace(/\{\{(\w+)\}\}/g, (_, key) => values[key]), '../');
    const dest = 'cad-' + createHash('sha256').update(rendered).update(await readFile(receiptFile)).update(record.imageSha256).digest('hex');
    modelFiles = {dest, still, receiptFile, rendered};
    release={study_path:readiness??null,source:record.source,receipt:record,
      derivatives:[path.join(folder,'assembly.png'),path.join(folder,'assembly.stl.gz'),config.receipt]};
    let motionLink='';
    if(config.playableGlb!==undefined){
      const relative=string(config.playableGlb,'playable CAD model');
      requireValue(path.extname(relative).toLowerCase()==='.glb','Expected an issued self-contained GLB');
      const glb=await projectFile(relative);
      const asset=await digest(glb)+'.glb';
      assets.set(asset,glb);
      release.derivatives.push(relative);
      motionLink=' · <a href="evidence/'+asset+'" download>Download the animated model</a>';
    }
    model = '<section><h2>Explore the CAD</h2><iframe title="'+values.title+'" loading="lazy" style="width:100%;height: min(48rem,85vh);border:0" src="'+dest+'/index.html"></iframe><p><a href="'+dest+'/index.html">Open the model full screen</a>'+motionLink+'</p></section>';
  }
  let coverage = '';
  if (data.inventory) {
    const file = await projectFile(data.inventory.file);
    requireValue(await digest(file) === data.inventory.sha256, 'Changed inventory mapping');
    const checker = fileURLToPath(new URL('./check-showcase-inventory.py', import.meta.url));
    const {stdout} = await promisify(execFile)(python,[checker,file,'--project',root],{encoding:'utf8',maxBuffer:8*1024*1024});
    const result = JSON.parse(stdout);
    requireValue(data.cad && result.revision === data.revision &&
      result.modelSha256 === JSON.parse(await readFile(modelFiles.receiptFile,'utf8')).meshSha256,
      'Inventory must match the featured CAD export and candidate revision');
    const rows = result.articles.map(row => '<tr><th scope="row">'+escape(row.id)+'</th><td>'+escape(row.subsystem)+'</td><td>'+
      escape(row.status)+'</td><td>'+escape(row.representation ?? row.reason)+'</td></tr>').join('');
    coverage = '<section><h2>Published assembly coverage</h2><p>'+escape(result.revision)+' · '+escape(result.pose)+' · '+escape(result.status)+
      '</p><details><summary>Inspect '+result.articles.length+' registered articles</summary><table><thead><tr><th>Article</th><th>Subsystem</th><th>Coverage</th><th>Representation</th></tr></thead><tbody>'+
      rows+'</tbody></table></details></section>';
  }
  let workflow = '';
  if (data.workflow !== undefined) {
    const url = new URL(data.workflow.revisionUrl);
    requireValue(url.protocol === 'https:' && url.hostname === 'github.com' && !url.username && !url.password &&
      !url.port && !url.search && !url.hash && /^\/[-.\w]+\/[-.\w]+\/blob\/[0-9a-f]{40}\/?$/.test(url.pathname),
      'Expected a public GitHub project URL pinned to a commit');
    const base = url.href.replace(/\/?$/, '/');
    const ref = url.pathname.split('/').filter(Boolean).at(-1);
    const rows = workflowRows(root,ref);
    requireValue(rows.length, 'Add at least one completed output to the published workflow index');
    const documentLink = item => '<a href="'+escape(item.url ?? (base+item.file.split('/').map(encodeURIComponent).join('/')))+'">'+escape(item.label)+'</a>';
    workflow = '<section id="workflow"><h2>Project workflow</h2><p>'+documentLink({file:'docs/workflow.md',label:'Open the versioned workflow index'})+
      '</p><table><thead><tr><th>Skill</th><th>Project output</th><th>Supporting evidence</th></tr></thead><tbody>'+
      rows.map(row => '<tr><th scope="row">'+escape(row.skill)+'</th><td>'+row.output.map(documentLink).join(', ')+'</td><td>'+
        (row.evidence.map(documentLink).join(', ') || escape(row.evidenceNote))+'</td></tr>').join('')+'</tbody></table></section>';
  }
  const student = publicFusionHandoff(root);
  if (student) {
    requireValue(student.revision===data.revision,'Public Fusion handoff revision differs from the showcase');
    const filename = student.sha256+path.extname(student.name).toLowerCase();
    assets.set(filename,student.file);
    workflow += '<section id="student-cad"><h2>Editable Fusion assembly</h2><p><a download="'+escape(path.basename(student.name))+
      '" href="evidence/'+filename+'">Download the student assembly</a> · '+escape(student.revision)+'</p><p>Native reopen evidence covers '+
      student.components+' named components and '+student.joints+' declared joints. Signed direction checked for '+student.signedJoints+' joints.</p></section>';
  }
  let lab;
  if (data.fieldLab !== undefined) {
    const spec=data.fieldLab;
    requireValue(spec.shareable===true && /^[a-f0-9]{64}$/.test(spec.sha256),'Confirm field lab redistribution and digest');
    const file=await projectFile(spec.file);
    const bytes=await readFile(file);
    requireValue(createHash('sha256').update(bytes).digest('hex')===spec.sha256,'Changed field lab');
    const markup=bytes.toString('utf8');
    requireValue(/<canvas\b[^>]*\bid=["']replayField["']/i.test(markup) && /\bid=["']rehearsal["']/i.test(markup),
      'Expected the project field lab with a match rehearsal');
    requireValue(!/<(?:script|img|iframe)\b[^>]*\bsrc\s*=\s*["'](?!data:)[^"']+/i.test(markup) &&
      !/<link\b[^>]*rel=["']stylesheet["'][^>]*href=["'](?!data:)/i.test(markup), 'Publish a self-contained field lab');
    const readme=await optionalRead(path.join(root,'README.md'));
    const links=Array.from((readme ?? '').matchAll(/\]\(([^)]+)\)/g),m=>m[1].split('#')[0]);
    requireValue(links.some(link=>(!link.includes(':') && path.resolve(root,link)===file) ||
      /^https:\/\/[^\s]+\/field-lab\.html$/.test(link)),'Link the project field lab from README.md');
    lab={bytes,sha256:spec.sha256};
  }
  const buildSection = build ? '<section id="build"><h2>Build sheet</h2><table><thead><tr><th>Subsystem</th><th>Configuration</th><th>Evidence</th></tr></thead><tbody>'+build+'</tbody></table></section>' : '';
  const fields = {title, role, revision, results, workflow, labLink:lab ? '<a href="field-lab.html">Open the field lab</a>' : '', buildSection, buildLink:build ? '<a href="#build">Build sheet</a>' : '',
    revisionLabel:stage === 'analysis' ? 'Analysis revision' : 'Candidate', model:model+coverage, media:media ? '<section id="media"><h2>Evidence gallery</h2>' + media + '</section>' : '',
    campaign, campaignLink:campaign ? '<a href="#campaign">Repeatability</a>' : '', mediaLink:media ? '<a href="#media">Gallery</a>' : '', themeFonts:inlineThemeFonts({families:['Source Sans 3']})};
  const html = applyStyle(template.replace(/\{\{(\w+)\}\}/g, (_, key) => fields[key]));
  const visuals=[...assets.values()].filter(asset=>/\.(?:png|jpe?g|webp|mp4|webm|pdf)$/i.test(asset));
  if(!release&&!student&&visuals.length){
    const known=JSON.parse(await readFile(new URL('../references/retained-teaching-display.json',import.meta.url),'utf8'));
    const pending=[];
    for(const visual of visuals){
      if(await digest(visual)===known.illustratedStroke)continue;
      let independent=false;
      if(process.env.FRC_VERIFIED_FIELD_ROOT){
        const approved=await realpath(process.env.FRC_VERIFIED_FIELD_ROOT);
        requireValue(approved!==root&&!within(root,approved),'Keep independently generated field media outside the candidate');
        const file=path.join(approved,path.relative(root,visual));
        try{independent=within(approved,await realpath(file))&&await digest(file)===await digest(visual);}catch(e){if(e.code!=='ENOENT')throw e;}
      }
      if(!independent)pending.push(path.relative(root,visual));
    }
    if(pending.length)release={study_path:data.mechanicalReadiness??null,source:null,derivatives:pending};
  }
  if(student || release){
    release??={study_path:data.mechanicalReadiness??null,source:null,derivatives:[]};
    if(release.source||student)for(const asset of visuals)release.derivatives.push(path.relative(root,asset));
    if(student)release.native=path.relative(root,student.file);
    await authorizeModel(python,root,release);
  }
  const publicConfig=await optionalRead(path.join(root,'cad-showcase.json'));
  if(publicConfig && (student || release)){
    const cfg=JSON.parse(publicConfig.replace(/^\uFEFF/,''));
    const featured=cfg.featuredAssembly ?? cfg.featured;
    if(featured){
      requireValue(featured.source && featured.still && featured.mesh,'Featured model needs a registered neutral source, still and mesh');
      await authorizeModel(python,root,{study_path:featured.mechanicalReadiness??null,source:featured.source,native:featured.archive??null,
        derivatives:[featured.still,featured.mesh]});
    }
  }
  await mkdir(directory, {recursive:true});
  const output = await realpath(directory);
  const page = path.join(output, 'index.html');
  const existing = await optionalRead(page);
  requireValue(existing === undefined || existing.split(/\r?\n/,1)[0] === marker, 'Existing page is independently authored. Choose another output directory.');
  if(lab){
    const target=path.join(output,'field-lab.html');
    let current;
    try{current=await digest(target);}catch(error){if(error.code!=='ENOENT')throw error;}
    if(current!==lab.sha256){
      const oldDigest=existing?.match(/<!-- published-field-lab ([a-f0-9]{64}) -->/)?.[1];
      requireValue(current===undefined || current===oldDigest,'Existing field-lab.html is independently authored or modified');
      const temporary=path.join(output,randomUUID()+'.tmp');
      try{await writeFile(temporary,lab.bytes);await rename(temporary,target);}finally{await rm(temporary,{force:true});}
    }
  }
  if (modelFiles) {
    const target = path.join(output,modelFiles.dest);
    await mkdir(target,{recursive:true});
    requireValue(await realpath(target) === target,'CAD directory is redirected');
    await copyFile(modelFiles.still,path.join(target,'assembly.png'));
    await copyFile(modelFiles.receiptFile,path.join(target,'receipt.json'));
    await writeFile(path.join(target,'index.html'),modelFiles.rendered);
  }
  const folder = path.join(output,'evidence');
  if (assets.size) {
    await mkdir(folder,{recursive:true});
    requireValue(await realpath(folder) === folder, 'Evidence directory is redirected');
  }
  for (const [name, input] of assets) {
    const dest = path.join(folder,name);
    const temp = path.join(folder,randomUUID() + '.tmp');
    try {
      await copyFile(input,temp);
      requireValue(await digest(temp) === path.parse(name).name,'Evidence changed during copy');
      await rename(temp,dest);
    } finally { await rm(temp,{force:true}); }
  }
  const tempPage = path.join(output,randomUUID() + '.tmp');
  try {
    await writeFile(tempPage,lab ? html+'\n<!-- published-field-lab '+lab.sha256+' -->\n' : html);
    await rename(tempPage,page);
  } finally { await rm(tempPage,{force:true}); }
  return page;
}


import { createHash, randomUUID } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { copyFile, mkdir, readFile, realpath, rename, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const marker = '<!-- Generated by Agent FRC robot-highlights -->';
const kinds = new Set(['modeled', 'measured', 'design', 'open']);
const assetTypes = new Set(['.csv', '.json', '.txt', '.pdf', '.jpg', '.jpeg', '.png', '.webp', '.mp4', '.webm']);
const escape = value => String(value).replace(/[&<>"']/g, char => ({'&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;'}[char]));
function requireValue(ok, message) { if (!ok) throw Error(message); }
function string(value, key) {
  requireValue(typeof value === 'string' && value.trim(), 'Missing ' + key);
  return value;
}
function list(value, key, required = false) {
  requireValue(Array.isArray(value) && (!required || value.length), 'Invalid ' + key);
  return value;
}
async function digest(file) {
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(file)) hash.update(chunk);
  return hash.digest('hex');
}
function within(root, file) {
  const relative = path.relative(root, file);
  return relative !== '..' && !relative.startsWith('..' + path.sep) && !path.isAbsolute(relative);
}
async function optionalRead(file) {
  try { return await readFile(file, 'utf8'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
}

export async function buildHighlights(manifest, directory) {
  const root = await realpath(path.dirname(manifest));
  const data = JSON.parse(await readFile(manifest, 'utf8'));
  requireValue(data.schema === 'agent-frc/robot-highlights@1', 'Unknown highlights schema');
  const title = escape(string(data.title, 'robot name'));
  const role = escape(string(data.role, 'robot role'));
  const revision = escape(string(data.revision, 'current candidate revision'));
  const assets = new Map();
  const sources = new Map();
  for (const ref of list(data.sources, 'sources', true)) {
    const id = string(ref.id, 'source ID');
    requireValue(!sources.has(id), 'Duplicate source ' + id);
    const label = string(ref.label, 'source label');
    const version = string(ref.revision, 'source revision');
    let href, type;
    if (ref.file !== undefined) {
      requireValue(!ref.url && ref.shareable === true, 'Confirm redistribution for ' + id);
      const name = string(ref.file, 'source file');
      requireValue(!path.win32.isAbsolute(name) && !path.isAbsolute(name), 'Expected relative file for ' + id);
      const file = await realpath(path.resolve(root, name));
      requireValue(within(root, file) && (await stat(file)).isFile(), 'Source outside project ' + id);
      type = path.extname(file).toLowerCase();
      requireValue(assetTypes.has(type), 'Unsupported evidence file type ' + type);
      requireValue(/^[a-f0-9]{64}$/.test(ref.sha256) && await digest(file) === ref.sha256, 'Changed evidence ' + id);
      const dest = ref.sha256 + type;
      href = 'evidence/' + dest;
      assets.set(dest, file);
    } else {
      const url = new URL(string(ref.url, 'evidence URL'));
      requireValue(url.protocol === 'https:' && !url.username && !url.password, 'Expected public HTTPS evidence URL');
      href = url.href;
    }
    sources.set(id, {label, version, href, type});
  }
  function source(id) {
    requireValue(sources.has(id), 'Unknown evidence reference ' + id);
    return sources.get(id);
  }
  function citation(id) {
    const s = source(id);
    return '<a href="' + escape(s.href) + '">' + escape(s.label) + '</a> <small>· ' + escape(s.version) + '</small>';
  }
  function kind(row) {
    requireValue(kinds.has(row.basis), 'Invalid evidence basis');
    return '<span class="basis">' + row.basis + '</span>';
  }
  const results = list(data.results, 'results', true).map(row =>
    '<article>' + kind(row) + '<h3>' + escape(string(row.claim, 'result')) + '</h3><p>' +
    escape(string(row.conditions, 'run conditions')) + '</p><p>' + escape(string(row.limit, 'result boundary')) +
    '</p><p>' + citation(row.source) + '</p></article>').join('');
  const build = list(data.build, 'build sheet', true).map(row =>
    '<tr><th scope="row">' + escape(string(row.subsystem, 'subsystem')) + '</th><td>' +
    escape(string(row.configuration, 'configuration')) + '</td><td>' + citation(row.source) + '</td></tr>').join('');
  const media = list(data.media ?? [], 'media').map(row => {
    const asset = source(row.asset);
    const caption = escape(string(row.caption, 'media description'));
    const alt = escape(string(row.description, 'media alternative'));
    let item;
    if (['.mp4', '.webm'].includes(asset.type)) {
      let poster = '';
      if (row.poster) {
        const image = source(row.poster);
        requireValue(['.png','.jpg','.jpeg','.webp'].includes(image.type), 'Expected local poster image');
        poster = ' poster="' + escape(image.href) + '"';
      }
      item = '<video controls playsinline preload="metadata" aria-label="' + alt + '"' + poster + ' src="' + escape(asset.href) + '"></video>';
    } else {
      requireValue(['.png','.jpg','.jpeg','.webp'].includes(asset.type), 'Expected local evidence image or film');
      item = '<img loading="lazy" alt="' + alt + '" src="' + escape(asset.href) + '">';
    }
    return '<figure>' + item + '<figcaption>' + caption + ' · ' + citation(row.source) + '</figcaption></figure>';
  }).join('');
  let campaign = '';
  if (data.campaign !== undefined) {
    const c = data.campaign;
    const counts = [c.total,c.passed,c.failed,c.unresolved,c.required];
    requireValue(counts.every(n => Number.isSafeInteger(n) && n >= 0) && c.required > 0 &&
      c.required <= c.total && c.passed + c.failed + c.unresolved === c.total, 'Invalid campaign counts');
    campaign = '<section id="campaign"><h2>Repeatability</h2><h3>' + escape(string(c.criterion,'campaign criterion')) +
      '</h3><p>Target ' + c.required + ' of ' + c.total + ' attempts. ' + c.passed + ' passed, ' + c.failed +
      ' failed, ' + c.unresolved + ' unresolved.</p><p>' + citation(c.source) + '</p></section>';
  }
  const template = await readFile(new URL('../templates/robot-highlights.html', import.meta.url), 'utf8');
  let model = '';
  let modelFiles;
  if (data.cad) {
    const config = data.cad;
    requireValue(config.shareable === true, 'Confirm CAD redistribution');
    async function projectFile(relative) {
      requireValue(typeof relative === 'string' && !path.win32.isAbsolute(relative) && !path.isAbsolute(relative), 'Expected relative CAD path');
      const file = await realpath(path.resolve(root,relative));
      requireValue(within(root,file) && (await stat(file)).isFile(), 'CAD file outside project');
      return file;
    }
    const receiptFile = await projectFile(config.receipt);
    const record = JSON.parse(await readFile(receiptFile,'utf8'));
    requireValue(record.schema === 'agent-frc/cad-still@1' && await digest(await projectFile(record.source)) === record.sourceSha256,'Changed CAD source');
    const folder = path.dirname(config.receipt);
    const still = await projectFile(path.join(folder,'assembly.png'));
    const mesh = await projectFile(path.join(folder,'assembly.stl.gz'));
    requireValue(await digest(still) === record.imageSha256 && await digest(mesh) === record.meshSha256, 'Changed CAD export');
    requireValue(Array.isArray(record.nativeBounds) && record.nativeBounds.length === 6 && record.nativeBounds.every(Number.isFinite), 'Invalid CAD bounds');
    const values = {title:escape(string(config.title,'assembly name')), scope:escape(string(config.scope,'CAD scope')),
      facts:escape(record.solids+' solids · '+record.triangles+' triangles · '+record.chordMm+' mm chord setting'),
      bounds:JSON.stringify(record.nativeBounds), mesh:(await readFile(mesh)).toString('base64')};
    const viewer = await readFile(new URL('../templates/cad-orbit.html',import.meta.url),'utf8');
    // Content-address the viewer directory so a later generation cannot change an earlier page's model.
    const rendered = viewer.replace(/\{\{(\w+)\}\}/g, (_, key) => values[key]);
    const dest = 'cad-' + createHash('sha256').update(rendered).update(await readFile(receiptFile)).update(record.imageSha256).digest('hex');
    modelFiles = {dest, still, receiptFile, rendered};
    model = '<section><h2>Explore the CAD</h2><iframe title="'+values.title+'" loading="lazy" style="width:100%;height: min(48rem,85vh);border:0" src="'+dest+'/index.html"></iframe><p><a href="'+dest+'/index.html">Open the model full screen</a></p></section>';
  }
  const fields = {title, role, revision, results, build, model, media:media ? '<section id="media"><h2>Evidence gallery</h2>' + media + '</section>' : '',
    campaign, campaignLink:campaign ? '<a href="#campaign">Repeatability</a>' : '', mediaLink:media ? '<a href="#media">Gallery</a>' : ''};
  const html = template.replace(/\{\{(\w+)\}\}/g, (_, key) => fields[key]);
  await mkdir(directory, {recursive:true});
  const output = await realpath(directory);
  const page = path.join(output, 'index.html');
  const existing = await optionalRead(page);
  requireValue(existing === undefined || existing.startsWith(marker + '\n'), 'Existing page is independently authored. Choose another output directory.');
  if (modelFiles) {
    const target = path.join(output,modelFiles.dest);
    await mkdir(target,{recursive:true});
    requireValue(await realpath(target) === target,'CAD directory is redirected');
    await copyFile(modelFiles.still,path.join(target,'assembly.png'));
    await copyFile(modelFiles.receiptFile,path.join(target,'receipt.json'));
    await writeFile(path.join(target,'index.html'),modelFiles.rendered);
  }
  const folder = path.join(output,'evidence');
  if (assets.size) {
    await mkdir(folder,{recursive:true});
    requireValue(await realpath(folder) === folder, 'Evidence directory is redirected');
  }
  for (const [name, input] of assets) {
    const dest = path.join(folder,name);
    const temp = path.join(folder,randomUUID() + '.tmp');
    try {
      await copyFile(input,temp);
      requireValue(await digest(temp) === path.parse(name).name,'Evidence changed during copy');
      await rename(temp,dest);
    } finally { await rm(temp,{force:true}); }
  }
  const tempPage = path.join(output,randomUUID() + '.tmp');
  try {
    await writeFile(tempPage,html);
    await rename(tempPage,page);
  } finally { await rm(tempPage,{force:true}); }
  return page;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    requireValue(process.argv.length === 4,'Usage: robot-highlights.mjs PROJECT-MANIFEST.json OUTPUT-DIRECTORY');
    console.log(await buildHighlights(process.argv[2],process.argv[3]));
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
